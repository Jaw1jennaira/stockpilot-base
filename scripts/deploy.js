// Deploy StockPilot to Base Sepolia (testnet only).
// Deployer = the fresh testnet agent key in state/agent-key.json.
// Requires Sepolia ETH from a faucet — if balance is 0, the script prints
// faucet instructions and exits (no funds are ever taken from user wallets).
const fs = require("fs");
const path = require("path");
const { ethers } = require("ethers");
const { CONFIG, loadKey } = require("../agent/config");
const { fetchBaseApiPrices, fetchYahooLatest } = require("../agent/prices");
const { toBytes32 } = require("../agent/prices");

function loadArtifact(name) {
  return JSON.parse(fs.readFileSync(path.join(__dirname, "..", "artifacts", `${name}.json`), "utf8"));
}

async function deploy(name, signer, ...args) {
  const art = loadArtifact(name);
  const factory = new ethers.ContractFactory(art.abi, art.bytecode, signer);
  const c = await factory.deploy(...args);
  await c.waitForDeployment();
  const addr = await c.getAddress();
  console.log(`deployed ${name} -> ${addr}`);
  return c;
}

async function main() {
  const key = loadKey();
  const provider = new ethers.JsonRpcProvider(CONFIG.rpcUrl);
  const wallet = new ethers.Wallet(key.privateKey, provider);
  console.log(`deployer/agent: ${wallet.address}`);
  const eth = await provider.getBalance(wallet.address);
  console.log(`Sepolia ETH: ${ethers.formatEther(eth)}`);
  if (eth === 0n) {
    console.log(`
NO SEPOLIA ETH — get testnet funds first (free, valueless):
  1. Copy this address: ${wallet.address}
  2. Try a Base Sepolia faucet, e.g.:
     - https://www.coinbase.com/faucets/base-ethereum-sepolia-faucet
     - https://faucet.quicknode.com/base/sepolia
     - https://www.alchemy.com/faucets/base-sepolia
  3. Re-run: npm run deploy
`);
    process.exit(1);
  }

  const usdc = await deploy("MockUSDC", wallet);
  const oracle = await deploy("StockOracle", wallet);
  const exchange = await deploy("StockExchange", wallet, await usdc.getAddress(), await oracle.getAddress());

  const stockAddresses = {};
  for (const t of CONFIG.tickers) {
    const token = await deploy(
      "MockStockToken",
      wallet,
      `${t.name} Tokenized Stock (Mirror)`,
      `m${t.ticker}`,
      await exchange.getAddress()
    );
    const addr = await token.getAddress();
    stockAddresses[t.ticker] = addr;
    let tx = await exchange.addTicker(toBytes32(t.ticker), addr);
    await tx.wait();
    tx = await exchange.fundInventory(toBytes32(t.ticker), BigInt(CONFIG.inventoryPerTicker) * 10n ** 8n);
    await tx.wait();
    console.log(`ticker ${t.ticker} added + inventory ${CONFIG.inventoryPerTicker} shares`);
  }

  const vault = await deploy("AgentVault", wallet, await usdc.getAddress(), await exchange.getAddress(), wallet.address);

  // Fund: mint mock USDC, seed exchange liquidity + vault.
  let tx = await usdc.mint(BigInt(100_000) * 10n ** 6n);
  await tx.wait();
  tx = await usdc.transfer(await exchange.getAddress(), BigInt(CONFIG.exchangeSeedUsdc) * 10n ** 6n);
  await tx.wait();
  tx = await usdc.transfer(await vault.getAddress(), BigInt(CONFIG.vaultSeedUsdc) * 10n ** 6n);
  await tx.wait();
  console.log(`funded exchange $${CONFIG.exchangeSeedUsdc} + vault $${CONFIG.vaultSeedUsdc} mock USDC`);

  for (const t of CONFIG.tickers) {
    tx = await vault.setTickerAllowed(toBytes32(t.ticker), true);
    await tx.wait();
  }
  console.log("vault tickers allowed");

  // Initial oracle prices from Base API (NAV), Yahoo fallback.
  let priceRes = await fetchBaseApiPrices().catch(() => ({ prices: {} }));
  if (!priceRes.prices || Object.keys(priceRes.prices).length === 0) {
    priceRes = await fetchYahooLatest();
  }
  const prices = {};
  for (const [ticker, v] of Object.entries(priceRes.prices || {})) prices[ticker] = v.price;
  if (Object.keys(prices).length) {
    const tickers = Object.keys(prices).map(toBytes32);
    const values = Object.values(prices).map((p) => BigInt(Math.round(p * 1e8)));
    tx = await oracle.postPrices(tickers, values);
    await tx.wait();
    console.log("oracle seeded:", prices);
  } else {
    console.log("WARN: no prices fetched — run the agent once to seed the oracle.");
  }

  const deployment = {
    network: "Base Sepolia",
    chainId: 84532,
    deployedAt: new Date().toISOString(),
    deployer: wallet.address,
    usdc: await usdc.getAddress(),
    oracle: await oracle.getAddress(),
    exchange: await exchange.getAddress(),
    vault: await vault.getAddress(),
    stocks: stockAddresses,
    explorer: "https://sepolia.basescan.org",
  };
  fs.writeFileSync(CONFIG.deploymentFile, JSON.stringify(deployment, null, 2));
  // Frontend config (public addresses only — no keys)
  fs.writeFileSync(
    path.join(__dirname, "..", "frontend", "config.js"),
    `// Auto-generated by scripts/deploy.js — public contract addresses only.\nwindow.STOCKPILOT = ${JSON.stringify(deployment, null, 2)};\n`
  );
  console.log("deployment saved:", CONFIG.deploymentFile);
  console.log(JSON.stringify(deployment, null, 2));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
